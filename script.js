const classListContainer = document.getElementById('classList');
const classFilter = document.getElementById('classFilter');
const searchInput = document.getElementById('searchInput');

function initFilterOptions() {
    classData.forEach(item => {
        const option = document.createElement('option');
        option.value = item.className;
        option.textContent = item.className;
        classFilter.appendChild(option);
    });
}

function renderData() {
    const selectedClass = classFilter.value;
    const searchTerm = searchInput.value.toLowerCase().trim();

    classListContainer.innerHTML = '';
    let totalVisibleStudents = 0;

    classData.forEach(item => {
        if (selectedClass !== 'ALL' && item.className !== selectedClass) {
            return;
        }
        
        const filteredStudents = item.students.filter(student => 
            student.name.toLowerCase().includes(searchTerm)
        );

        if (filteredStudents.length > 0) {
            totalVisibleStudents += filteredStudents.length;
            
            const classSection = document.createElement('div');
            classSection.className = 'class-section';

            const classTitle = document.createElement('h2');
            classTitle.className = 'class-title';
            classTitle.textContent = item.className;

            const studentGrid = document.createElement('div');
            studentGrid.className = 'student-grid';
            
            filteredStudents.forEach(student => {
                const studentCard = document.createElement('div');
                studentCard.className = 'student-card';

                const studentName = document.createElement('span');
                studentName.className = 'student-name';
                studentName.textContent = student.name;

                studentCard.appendChild(studentName);
                
                if (student.link.trim() !== "") {
                    const igLink = document.createElement('a');
                    igLink.className = 'ig-link';
                    igLink.href = student.link;
                    igLink.target = '_blank';
                    igLink.rel = 'noopener noreferrer';
                    igLink.innerHTML = `<i class="fa-brands fa-instagram"></i> Instagram`;
                    studentCard.appendChild(igLink);
                } else {
                    const emptyBadge = document.createElement('span');
                    emptyBadge.className = 'empty-badge';
                    emptyBadge.textContent = 'Belum ada akun';
                    studentCard.appendChild(emptyBadge);
                }

                studentGrid.appendChild(studentCard);
            });

            classSection.appendChild(classTitle);
            classSection.appendChild(studentGrid);
            classListContainer.appendChild(classSection);
        }
    });

    if (totalVisibleStudents === 0) {
        classListContainer.innerHTML = `<div class="no-result">Tidak ada data siswa yang ditemukan.</div>`;
    }
}

searchInput.addEventListener('input', renderData);
classFilter.addEventListener('change', renderData);

initFilterOptions();
renderData();


